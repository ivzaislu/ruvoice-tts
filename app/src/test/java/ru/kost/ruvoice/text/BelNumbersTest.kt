    @Test
    fun ordinalSuffixes() {
        // форма по суффиксу; не проверено носителем
        assertEquals("першага верасня", prep("1-га верасня"))
        assertEquals("пяты клас", prep("5-ы клас"))
        assertEquals("другі", prep("2-гі"))
        assertEquals("трэці", prep("3-ці"))
        assertEquals("у пятым класе", prep("у 5-м класе"))
        assertEquals("у тысяча дзевяцьсот дзевяностыя гады.", prep("у 1990-я гг."))
        // «-я» не у десятилетия — назоўны ж. р.
        assertEquals("пятая кніга", prep("5-я кніга"))
        assertEquals("дзясятая кніга", prep("10-я кніга"))
        // десятилетие: «-я» — назоўны мн., «-х» — родны/месны мн.; круглая тысяча с «-я» — ж. р., если не «гады» за ней
        assertEquals("гэта было ў васьмідзясятыя гады.", prep("Гэта было ў 80-я гады."))
        assertEquals("у тысяча дзевяцьсот дзевяностых гадах", prep("у 1990-х гадах"))
        assertEquals("у дзевяностых", prep("у 90-х"))
        assertEquals("у двухтысячных", prep("у 2000-х"))
        assertEquals("у двухтысячныя гады", prep("у 2000-я гады"))
        assertEquals("тысячная старонка", prep("1000-я старонка"))
        // «2-х»…«4-х» — количественное; «-й» (русский) — порядковое м. р.
        assertEquals("адзін з трох.", prep("Адзін з 3-х."))
        assertEquals("у двух кіламетрах", prep("у 2-х кіламетрах"))
        assertEquals("яна — другі", prep("яна — 2-й"))
        assertEquals("яго другі дом", prep("яго 2-й дом"))
    }

