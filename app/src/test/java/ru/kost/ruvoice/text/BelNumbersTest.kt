    }

    @Test
    fun yearFromTo() {
        // «з … па … г.» — оба года порядковым, как у русского «с 1941-го по 1945-й год». Не проверено носителем
        val y41 = "тысяча дзевяцьсот сорак першага"
        assertEquals("з $y41 па тысяча дзевяцьсот сорак пяты год.", prep("З 1941 па 1945 г."))
        assertEquals("з $y41 па тысяча дзевяцьсот сорак пяты год.", prep("з 1941 па 1945 гг."))
        assertEquals("з $y41 да тысяча дзевяцьсот сорак пятага года.", prep("з 1941 да 1945 г."))
        assertEquals("ад $y41 да тысяча дзевяцьсот сорак пятага года.", prep("ад 1941 да 1945 гг."))
        assertEquals("з $y41 па тысяча дзевяцьсот сорак пяты год. потым", prep("з 1941 г. па 1945 г. Потым"))
        // без «г.» — не годы
        assertEquals("з адной тысячы да дзвюх тысяч рублёў", prep("з 1000 да 2000 рублёў"))
    }

