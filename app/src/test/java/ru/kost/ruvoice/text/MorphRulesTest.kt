/** Правила нормализатора, которым нужна таблица морфологии (Normalizer.morph); без неё их проверяют NumbersTest/CasesTest. */
class MorphRulesTest {
    private fun n(s: String) = Normalizer.numbers(s)

    @Before fun load() { Normalizer.morph = Morph.open(File(TestData.root(), "app/src/main/assets/morph.bin")) }
    @After fun unload() { Normalizer.morph = null }

    @Test fun trillionsBeforeNounNoCrash() {
        // final-rereview-6: число от триллиона перед существительным шло в cardinal/Declension.cardinal, где старшим
        // разрядом был миллиард, и below1000 падал на hundreds[10] (ArrayIndexOutOfBounds в TTS-пути)
        val allowed = "_~|!+,-.:;?абвгдежзийклмнопрстуфхцчшщъыьэюяё–… "
        fun p(s: String) = Splitter.sentences(s).joinToString(" | ") { Normalizer.prepare(it, allowed) }
        assertEquals("общая масса шариков составляла один триллион двадцать шесть миллиардов килограммов.",
            p("Общая масса шариков составляла 1 026 000 000 000 килограммов."))
        assertEquals("один триллион двадцать шесть миллиардов килограммов", p("1026000000000 килограммов"))
        assertEquals("около одного триллиона двадцати шести миллиардов рублей.", p("Около 1 026 000 000 000 рублей."))
        assertEquals("с одним триллионом двадцатью шестью миллиардами людьми", p("С 1 026 000 000 000 людьми"))
        assertEquals("тридцать три триллиона тонн", p("33 000 000 000 000 тонн"))
        assertEquals("о девяти квинтиллионах двухстах двадцати трёх квадриллионах трёхстах семидесяти двух триллионах тридцати " +
            "шести миллиардах восьмистах пятидесяти четырёх миллионах семистах семидесяти пяти тысячах восьмистах семи звёздах.",
            p("О 9 223 372 036 854 775 807 звёздах."))
        // длиннее Long: toLong в деньгах, дроби, номере раздела, степени падал — теперь правило пропускает число,
        // его читает общий путь по цифрам
        val z = List(17) { "ноль" }.joinToString(" ")
        assertEquals("девять три $z рублей тридцать копеек", p("9 300 000 000 000 000 000 руб. 30 коп."))
        assertEquals("один девять три $z", p("1/9 300 000 000 000 000 000"))
        assertEquals("девять три $z точка двенадцать точка две тысячи двадцать", p("9 300 000 000 000 000 000.12.2020"))
        val digits23 = "один два три четыре пять шесть семь восемь девять ноль один два три четыре пять шесть семь восемь девять ноль один два три"
        assertEquals("$digits23 $digits23", p("12345678901234567890123/12345678901234567890123"))
        // степень и центы при числе длиннее Long теряются (фильтр знаков), но слова есть и цифр не остаётся
        assertEquals("десять", p("10⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹"))
        assertEquals("$digits23 доллара", p("\$12345678901234567890123.50"))
        // голое число длиннее 12 цифр — по-прежнему по цифрам (NumbersTest.longNumberDigitByDigit)
        assertEquals("один ноль два шесть ноль ноль ноль ноль ноль ноль ноль ноль ноль", p("1 026 000 000 000"))
    }

    @Test fun timeAfterVBeforeNoun() {
        // ревью ru-fixes I1: «в ч.мм» отдано времени, но существительное следом оставляет число (было «в первого октября раза»)
        assertEquals("скидка в одну целую десять сотых раза.", Normalizer.prepare("Скидка в 1.10 раза.", "_~|!+,-.:;?абвгдежзийклмнопрстуфхцчшщъыьэюяё–… "))
    }

    private fun pr(s: String) = Splitter.sentences(s).joinToString(" | ") {
        Normalizer.prepare(it, "_~|!+,-.:;?абвгдежзийклмнопрстуфхцчшщъыьэюяё–… ") }

    @Test fun percentAfterTimePreposition() {
        // повторное ревью ru-fixes O1: «до 7.25%» читалось временем, знак процента терялся
        assertEquals("инфляция замедлилась до семи целых двадцати пяти сотых процента.", pr("Инфляция замедлилась до 7.25%."))
        assertEquals("ставка выросла с семи целых пятидесяти сотых процента до восьми целых двадцати пяти сотых процента.",
            pr("Ставка выросла с 7.50% до 8.25%."))
        assertEquals("работаем с девяти часов до восемнадцати часов.", pr("Работаем с 9.00 до 18.00."))
    }

    @Test fun okBeforeNumberReadsAround() {
        // «ок.» после обычного слова перед числом — «около» (Splitter не режет фразу), в реплике — «ок» и пауза
        assertEquals("расстояние около трёхсот километров.", pr("Расстояние ок. 300 км."))
        assertEquals("ну ок. | два часа ждать придётся.", pr("Ну ок. 2 часа ждать придётся."))
    }

    @Test fun decimalBeforeAgreeingNoun() {
        // «2 тысячи» → «две» брало дробную часть десятичной за число: «один,две тысячи», «ноль,две секунды»
        assertEquals("продано одна целая две десятых тысячи книг.", pr("Продано 1,2 тысячи книг."))
        assertEquals("продано одна целая двадцать две сотых тысячи книг.", pr("Продано 1.22 тысячи книг."))
        assertEquals("статья одна целая две десятых тысячи рублей", pr("Статья 1.2 тысячи рублей"))
        assertEquals("на рынке пятнадцать целых две десятых тысячи квартир.", pr("На рынке 15,2 тысячи квартир."))
        assertEquals("груз весил одну целую две десятых тонны.", pr("Груз весил 1,2 тонны."))
        assertEquals("прошло ноль целых две десятых секунды.", pr("Прошло 0,2 секунды."))
        assertEquals("перевезли одну целую одну десятую тонну груза.", pr("Перевезли 1,1 тонну груза."))
        assertEquals("продано две тысячи книг.", pr("Продано 2 тысячи книг."))
        assertEquals("продано полторы тысячи книг.", pr("Продано 1,5 тысячи книг."))
    }

    @Test fun sectionLabelBeforeScale() {
        // повторное ревью ru-fixes R2: разряд за числом — количество, не номер раздела
        assertEquals("в обеих частях полторы тысячи страниц.", pr("В обеих частях 1.5 тыс. страниц."))
        assertEquals("статьи полтора миллиона просмотров.", pr("Статьи 1.5 млн просмотров."))
        assertEquals("частью два точка один статьи триста тридцать два", pr("частью 2.1 статьи 332"))
    }

    @Test fun decimalBeforeDativeOrInstrumentalPlural() {
        // повторное ревью ru-fixes R3: точка оставалась внутри слов («с два.пятьюдесятью рублями»); падеж дроби — именительный
        assertEquals("в четырнадцать целых шестьдесят пять сотых спасателям поступило", pr("в 14.65 спасателям поступило"))
        assertEquals("с две целых пятьдесят сотых рублями", pr("с 2.50 рублями"))
        assertEquals("сумма равна две целых пятьдесят сотых рублям.", pr("Сумма равна 2.50 рублям."))
    }

    @Test fun changeVerbBeforeNaIsNotDate() {
        // повторное ревью ru-fixes R4: «вырос на 2.08.» — изменение величины; «по России на 2.08.» — дата
        assertEquals("вэ вэ п+э вырос на две целых восемь сотых.", pr("ВВП вырос на 2.08."))
        assertEquals("акции подешевели на две целых пять сотых.", pr("Акции подешевели на 2.05."))
        assertEquals("данные по россии на второе августа.", pr("Данные по России на 2.08."))
        assertEquals("курс на второе августа.", pr("Курс на 2.08."))
    }

    @Test fun scaleAfterDateShapedNumber() {
        // ревью ru-fixes N1: «дд.д тыс./млн» — количество, не «двенадцатого января тысяч»; дата с годом — по-прежнему дата
        assertEquals("статья двенадцать целых одна десятая тысячи рублей", pr("Ст. 12.1 тыс. руб."))
        assertEquals("в разделе двенадцать с половиной тысяч строк.", pr("В разделе 12.5 тыс. строк."))
        assertEquals("возбуждено двенадцать целых одна десятая тысячи дел.", pr("Возбуждено 12.1 тыс. дел."))
        assertEquals("на первое января две тысячи двадцать четвёртого года тысяч рублей", pr("На 01.01.2024 тыс. руб."))
    }

    @Test fun scaleOnlyInFormsAfterDecimal() {
        // ревью ru-fixes раунд 3, M1: разряд отменяет дату только в формах после дроби и не у дня с нулём; процент — всегда
        assertEquals("к первому сентября миллионы школьников пойдут в школу.", pr("К 01.09 миллионы школьников пойдут в школу."))
        assertEquals("на первое января тысяч рублей", pr("На 01.01 тыс. руб."))
        assertEquals("глава один точка два тысяча и одна ночь.", pr("Глава 1.2 Тысяча и одна ночь."))
        assertEquals("индекс вырос на одну целую пять сотых процента.", pr("Индекс вырос на 01.05 %."))
    }

    @Test fun changeVerbNeedsWordBoundary() {
        // ревью ru-fixes N2: «подросткам» — не «подрос»
        assertEquals("билеты подросткам на первое сентября.", pr("Билеты подросткам на 1.09."))
        assertEquals("цены выросли на две целых восемь сотых.", pr("Цены выросли на 2.08."))
        assertEquals("курс снизился на одну целую пять сотых.", pr("Курс снизился на 1.05."))
    }

    @Test fun percentAfterDateShapedNumber() {
        // ревью ru-fixes O2: «1.05%» — процент, знак не теряется
        assertEquals("инфляция составила одну целую пять сотых процента.", pr("Инфляция составила 1.05%."))
        assertEquals("по две целых восемь сотых процента за квартал", pr("по 2.08 % за квартал"))
        assertEquals("сегодня двенадцатого мая.", pr("Сегодня 12.05."))
    }

    @Test fun sectionLabelBeforeSpelledScale() {
        // ревью ru-fixes, хвост R2: разряд словом — тоже количество
        assertEquals("в обеих частях полторы тысячи страниц.", pr("В обеих частях 1.5 тысячи страниц."))
        assertEquals("статьи полтора миллиона просмотров.", pr("Статьи 1.5 миллиона просмотров."))
        // «тысячелетия» — не разряд
        assertEquals("глава два точка один тысячелетия.", pr("Глава 2.1 тысячелетия."))
    }

    @Test fun genderAfterOne() {
        assertEquals("одна ночь", n("1 ночь"))
        assertEquals("один конь", n("1 конь"))
        assertEquals("один путь", n("1 путь"))
        assertEquals("одно такси", n("1 такси"))
        assertEquals("одно сообщение", n("1 сообщение"))
        assertEquals("одно время", n("1 время"))
        assertEquals("двадцать одна минута", n("21 минута"))
        assertEquals("одну книгу", n("1 книгу"))
        assertEquals("одного коня", n("1 коня"))
        // общий род — по старой эвристике (окончание -а)
        assertEquals("одна сирота", n("1 сирота"))
        // неизвестное слово — по старой эвристике
        assertEquals("одна абракадабра", n("1 абракадабра"))
        // не существительное — не трогаем
        assertEquals("на один больше", n("на 1 больше"))
    }

    @Test fun genderAfterTwo() {
        assertEquals("две двери", n("2 двери"))
        assertEquals("две ночи", n("2 ночи"))
        assertEquals("два стола", n("2 стола"))
        assertEquals("два сообщения", n("2 сообщения"))
        assertEquals("пять минут", n("5 минут"))
    }

    @Test fun caseByNoun() {
        assertEquals("одному другу", n("1 другу"))
        assertEquals("в одном доме", n("в 1 доме"))
        assertEquals("одной двери", n("1 двери"))
        assertEquals("двадцатью одним столом", n("21 столом"))
        assertEquals("пятью путями", n("5 путями"))
        assertEquals("семи гномам", n("7 гномам"))
        assertEquals("трёх друзей", n("3 друзей"))
        assertEquals("два–три рабочих дня", n("2–3 рабочих дня"))
        assertEquals("пять друзей", n("5 друзей"))
        assertEquals("пять минут", n("5 минут"))
        assertEquals("пять программ", n("5 программ"))
        assertEquals("два стола", n("2 стола"))
        // именительный/винительный — как раньше
        assertEquals("три дня", n("3 дня"))
        assertEquals("около пятисот рублей", n("около 500 рублей"))
    }

    // «новых» в таблице — и прилагательное, и субстантив: после числа это род. мн., не предложный «о двух новых»
    // (TalkBack в Telegram: «2 новых сообщения» звучало «двух новых сообщения»)
    @Test fun adjectiveAfterNumber() {
        assertEquals("два новых сообщения", n("2 новых сообщения"))
        assertEquals("три непрочитанных сообщения", n("3 непрочитанных сообщения"))
        assertEquals("двадцать два новых уведомления", n("22 новых уведомления"))
        assertEquals("пять новых сообщений", n("5 новых сообщений"))
        assertEquals("десять новых уведомлений", n("10 новых уведомлений"))
        assertEquals("Чат, Иван, четыре новых сообщения", n("Чат, Иван, 4 новых сообщения"))
        assertEquals("Непрочитанных: пять", n("Непрочитанных: 5"))
        assertEquals("два новых", n("2 новых"))
        assertEquals("два учёных", n("2 учёных"))
        assertEquals("две непрочитанных заявки", n("2 непрочитанных заявки"))
        assertEquals("сорок две новых записи", n("42 новых записи"))
        assertEquals("двенадцать новых заявок", n("12 новых заявок"))
        // падеж задаёт предлог или существительное следом
        assertEquals("из пяти новых сообщений", n("из 5 новых сообщений"))
        assertEquals("из двух новых сообщений", n("из 2 новых сообщений"))
        assertEquals("в двух новых домах", n("в 2 новых домах"))
        assertEquals("к двум новым сообщениям", n("к 2 новым сообщениям"))
        // творительный по прилагательному «-ыми» и с числом на 1
        assertEquals("с двадцатью одним новыми сообщениями", n("с 21 новыми сообщениями"))
        assertEquals("с двадцатью двумя новыми сообщениями", n("с 22 новыми сообщениями"))
        // круглая тысяча перед предложным — не винительный «одну тысячу»; «за 1000 рублей» — по-прежнему он
        assertEquals("в одной тысяче новых чатах", n("в 1000 новых чатах"))
        assertEquals("в одной тысяче чатах", n("в 1000 чатах"))
        assertEquals("за одну тысячу рублей", n("за 1000 рублей"))
        // «об» перед числом словами на гласную
        assertEquals("об одной заявке", n("о 1 заявке"))
        assertEquals("об одиннадцати заявках", n("о 11 заявках"))
        assertEquals("о пяти заявках", n("о 5 заявках"))
        assertEquals("о восьми заявках", n("о 8 заявках"))
    }

    @Test fun caseByAdjective() {
        assertEquals("последних двадцати-тридцати лет", n("последних 20-30 лет"))
        assertEquals("первых пяти минут", n("первых 5 минут"))
        assertEquals("в последних пяти случаях", n("в последних 5 случаях"))
        assertEquals("последним пяти годам", n("последним 5 годам"))
        assertEquals("за последние пять лет", n("за последние 5 лет"))
        assertEquals("первые три дня", n("первые 3 дня"))
        // одушевлённое: «-их» — родительный или винительный, оставляем
        assertEquals("последних пять друзей", n("последних 5 друзей"))
    }

    @Test fun adjectiveAbbreviations() {
        assertEquals("снижение государственного контроля", n("снижение гос. контроля"))
        assertEquals("положение официальной часовой стрелки", n("положение офиц. часовой стрелки"))
        assertEquals("порядок государственной часовой службы", n("порядок гос. часовой службы"))
        assertEquals("Государственная служба", n("Гос. служба"))
        assertEquals("в государственных органах", n("в гос. органах"))
        assertEquals("техническое задание", n("тех. задание"))
        assertEquals("с греческого языка", n("с греч. языка"))
        assertEquals("от латинского homo", n("от лат. homo"))
        // «службы» — Р.п. ед. или И./В.п. мн.: решает существительное перед сокращением
        assertEquals("порядок государственной службы", n("порядок гос. службы"))
        assertEquals("реформа международного контроля и политической системы", n("реформа междунар. контроля и полит. системы"))
        assertEquals("проверил гос. службы", n("проверил гос. службы"))
        assertEquals("все гос. службы", n("все гос. службы"))
        assertEquals("правительство и гос. службы", n("правительство и гос. службы"))
        // «ж/д» — прилагательное в роде и падеже существительного, без него после предлога — «железная дорога»
        assertEquals("железнодорожная станция", n("ж/д станция"))
        assertEquals("до железнодорожного вокзала", n("до ж/д вокзала"))
        assertEquals("на железнодорожных путях", n("на ж/д путях"))
        assertEquals("по железной дороге можно доехать", n("по ж/д можно доехать"))
        assertEquals("до железной дороги.", n("до ж/д."))
        // неизвестное слово следом — как было
        assertEquals("гос. абырвалг", n("гос. абырвалг"))
    }

