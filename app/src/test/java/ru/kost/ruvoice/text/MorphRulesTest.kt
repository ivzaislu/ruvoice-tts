    @Test fun decimalInObliqueCase() {
        assertEquals("к семи целым пяти десятым года он вырос.", pr("К 7,5 годам он вырос."))
        assertEquals("к семи целым пяти десятым года.", pr("К 7,5 года."))
        assertEquals("смешать с одной целой пятью десятыми литра воды.", pr("Смешать с 1,5 литрами воды."))
        assertEquals("в двух целых пяти десятых метра от дома.", pr("В 2,5 метрах от дома."))
        assertEquals("при тридцати шести целых шести десятых градуса.", pr("При 36,6 градусах."))
        assertEquals("о двух целых пяти десятых процента.", pr("О 2,5 процентах."))
        assertEquals("перед двумя целыми пятью десятыми тысячи.", pr("Перед 2,5 тысячами."))
        assertEquals("к двум целым пяти десятым процента.", pr("К 2,5%."))
        assertEquals("при одной целой пяти десятых процента.", pr("При 1,5%."))
        assertEquals("по две целых восемь сотых процента.", pr("По 2,08%."))
        assertEquals("в среднем с девятью целыми четырьмя десятыми очка и четырьмя целыми восьмью десятыми подбора.",
            pr("В среднем с 9,4 очками и 4,8 подборами."))
        assertEquals("с шестью целыми пятьюдесятью сотыми силы.", pr("С 6,50 силами."))
        // целая часть с нулём впереди, «.00», предлог другого падежа перед числом — время или не тот падеж, не трогаем
        assertEquals("по шесть целых пятьдесят сотых силами.", pr("По 06.50 силами."))
        assertEquals("в четырнадцать целых тридцать сотых ударами волн.", pr("В 14.30 ударами волн."))
        assertEquals("к семнадцать целых ноль сотых уже были.", pr("К 17.00 уже были."))
        // ревью ru-fixes-2 M-2, M-3: после «ноль», «тысяча» — «целых»; «минус» словом; «людьми», «детьми»
        assertEquals("с нулём целых пятью десятыми литра.", pr("С 0,5 литрами."))
        assertEquals("к нулю целых пяти десятым литра.", pr("К 0,5 литрам."))
        assertEquals("с одной тысячей целых пятью десятыми рубля.", pr("С 1000,5 рублями."))
        assertEquals("при минус двух целых пяти десятых градуса.", pr("При минус 2,5 градусах."))
        assertEquals("с двумя целыми пятью десятыми человека.", pr("С 2,5 людьми."))
        assertEquals("с двумя целыми пятью десятыми ребёнка.", pr("С 2,5 детьми."))
        // номер версии — не количество
        assertEquals("версия две целых ноль десятых пользователям доступна.", pr("Версия 2.0 пользователям доступна."))
        // винительный и родительный — как было; полтора — где было
        assertEquals("цена выросла в одну целую пять десятых раза.", pr("Цена выросла в 1,5 раза."))
        assertEquals("около двух целых пяти десятых метров.", pr("Около 2,5 метров."))
        assertEquals("около полутора миллионов человек.", pr("Около 1,5 млн человек."))
        assertEquals("продано полторы тысячи книг.", pr("Продано 1,5 тысячи книг."))
    }

