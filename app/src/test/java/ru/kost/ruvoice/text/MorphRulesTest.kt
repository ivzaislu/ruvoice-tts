    @Test fun trillionsBeforeNounNoCrash() {
        // final-rereview-6: число от триллиона перед существительным шло в cardinal/Declension.cardinal, где старшим
        // разрядом был миллиард, и below1000 падал на hundreds[10] (ArrayIndexOutOfBounds в TTS-пути)
        val allowed = "_~|!+,-.:;?абвгдежзийклмнопрстуфхцчшщъыьэюяё–… "
        fun p(s: String) = Splitter.sentences(s).joinToString(" | ") { Normalizer.prepare(it, allowed) }
        assertEquals("общая масса шариков составляла один триллион двадцать шесть миллиардов килограммов.",
            p("Общая масса шариков составляла 1 026 000 000 000 килограммов."))
        assertEquals("один триллион двадцать шесть миллиардов килограммов", p("1026000000000 килограммов"))
        assertEquals("около одного триллиона двадцати шести миллиардов рублей.", p("Около 1 026 000 000 000 рублей."))
        assertEquals("с одним триллионом двадцатью шестью миллиардами людьми", p("С 1 026 000 000 000 людьми"))
        assertEquals("тридцать три триллиона тонн", p("33 000 000 000 000 тонн"))
        assertEquals("о девяти квинтиллионах двухстах двадцати трёх квадриллионах трёхстах семидесяти двух триллионах тридцати " +
            "шести миллиардах восьмистах пятидесяти четырёх миллионах семистах семидесяти пяти тысячах восьмистах семи звёздах.",
            p("О 9 223 372 036 854 775 807 звёздах."))
        // длиннее Long: toLong в деньгах, дроби, номере раздела, степени падал — теперь правило пропускает число,
        // его читает общий путь по цифрам
        val z = List(17) { "ноль" }.joinToString(" ")
        assertEquals("девять три $z рублей тридцать копеек", p("9 300 000 000 000 000 000 руб. 30 коп."))
        assertEquals("один девять три $z", p("1/9 300 000 000 000 000 000"))
        assertEquals("девять три $z точка двенадцать точка две тысячи двадцать", p("9 300 000 000 000 000 000.12.2020"))
        val digits23 = "один два три четыре пять шесть семь восемь девять ноль один два три четыре пять шесть семь восемь девять ноль один два три"
        assertEquals("$digits23 $digits23", p("12345678901234567890123/12345678901234567890123"))
        // степень и центы при числе длиннее Long теряются (фильтр знаков), но слова есть и цифр не остаётся
        assertEquals("десять", p("10⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹⁹"))
        assertEquals("$digits23 доллара", p("\$12345678901234567890123.50"))
        // голое число длиннее 12 цифр — по-прежнему по цифрам (NumbersTest.longNumberDigitByDigit)
        assertEquals("один ноль два шесть ноль ноль ноль ноль ноль ноль ноль ноль ноль", p("1 026 000 000 000"))
    }

