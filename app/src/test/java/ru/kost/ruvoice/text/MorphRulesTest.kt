    @Test fun yearGWeightContext() {
        // ревью ru-fixes-2 I-1: вес по контексту — граммы, как в базе; год рядом — по-прежнему год
        assertEquals("растворите в десяти граммах спирта.", pr("Растворите в 10 г. спирта."))
        assertEquals("в пятнадцати граммах семян много белка.", pr("В 15 г. семян много белка."))
        assertEquals("в тридцати граммах миндаля шесть граммов белка.", pr("В 30 г. миндаля 6 г. белка."))
        assertEquals("монета весила около восьми граммов.", pr("Монета весила ок. 8 г."))
        assertEquals("вес монеты около восьми граммов.", pr("Вес монеты ок. 8 г."))
        assertEquals("монета, около восьми граммов. из серебра.", pr("Монета (ок. 8 г.) из серебра."))
        assertEquals("ингредиенты: гвоздика, два грамма. корица, три грамма..", pr("Ингредиенты: гвоздика (2 г.), корица (3 г.)."))
        assertEquals("масса шарика, пятнадцать граммов. мала.", pr("Масса шарика (15 г.) мала."))
        assertEquals("потом ещё, тридцать пять граммов. сахара.", pr("Потом ещё (35 г.) сахара."))
        assertEquals("хорошо, ок. | десять граммов возьму.", pr("Хорошо, ок. 10 г. возьму."))
        assertEquals("в девяностодевятитысячном году до нашей эры", pr("в 99000 г. до н. э."))
        assertEquals("в девяностооднотысячном году до нашей эры", pr("в 91000 г. до н. э."))
        // годы
        assertEquals("умер около девятьсот девяностого года в альтдорфе.", pr("Умер ок. 990 г. в Альтдорфе."))
        assertEquals("сослал дочь во втором году на остров.", pr("Сослал дочь во 2 г. на остров."))
        assertEquals("гунны напали на галлию, четыреста пятьдесят первый год.", pr("Гунны напали на Галлию (451 г.)."))
        // повторное ревью ru-fixes-2 M-a: слово о времени следом и вес в переносном смысле — год
        assertEquals("во втором году войны он погиб.", pr("Во 2 г. войны он погиб."))
        assertEquals("в двенадцатом году правления августа был мир.", pr("В 12 г. правления Августа был мир."))
        assertEquals("в пятом году царствования петра.", pr("В 5 г. царствования Петра."))
        assertEquals("в седьмом году жизни петра.", pr("В 7 г. жизни Петра."))
        assertEquals("в массе своей крестьяне в пятнадцатом году жили бедно.", pr("В массе своей крестьяне в 15 г. жили бедно."))
        assertEquals("его вес в обществе вырос в двенадцатом году при нероне.", pr("Его вес в обществе вырос в 12 г. при Нероне."))
        assertEquals("в десяти граммах соли.", pr("В 10 г. соли."))
        // ревью ru-fixes-2 N-1: «в массе» без «своей» и прилагательное перед «вес» — прямой смысл, граммы
        assertEquals("доля серебра в массе монеты около тридцати граммов.", pr("Доля серебра в массе монеты ок. 30 г."))
        assertEquals("содержание золота в массе сплава около пятидесяти граммов.", pr("Содержание золота в массе сплава ок. 50 г."))
        assertEquals("растворено в массе около двадцати граммов.", pr("Растворено в массе ок. 20 г."))
        assertEquals("общественный вес монеты около тридцати граммов.", pr("Общественный вес монеты ок. 30 г."))
    }

