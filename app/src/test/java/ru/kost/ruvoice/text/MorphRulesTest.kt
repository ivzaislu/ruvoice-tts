    @Test fun complaintsOct28Numbers() {
        // жалоба 28.10.2026: тысяча на 1 после «в/за» — женская, остаток по роду существительного следом
        val allowed = "_~|!+,-.:;?абвгдежзийклмнопрстуфхцчшщъыьэюяё–… "
        fun p(s: String) = Normalizer.prepare(s, allowed)
        assertEquals("превышение в одну тысячу триста сорок один раз.", p("Превышение в 1341 раз."))
        assertEquals("в одну тысячу триста сорок два раза больше.", p("В 1342 раза больше."))
        assertEquals("за одну тысячу два рубля.", p("За 1002 рубля."))
        assertEquals("получил одну тысячу один голос.", p("Получил 1001 голос."))
        assertEquals("за одну тысячу одну ночь.", p("За 1001 ночь."))
        assertEquals("на одну тысячу две книги.", p("На 1002 книги."))
        assertEquals("за одну тысячу одну новую книгу.", p("За 1001 новую книгу."))
        // «ЛжеДмитрий II» — имя слитно с заглавной внутри
        assertEquals("лжедмитрий второй пришёл.", p("ЛжеДмитрий II пришёл."))
        assertEquals("лжедмитрий первый пришёл.", p("ЛжеДмитрий I пришёл."))
        assertEquals("при лжедмитрии втором было плохо.", p("При ЛжеДмитрии II было плохо."))
        // «4 820 / 11 000» — одно число, слэш с пробелами как слитный
        assertEquals("набрано: четыре тысячи восемьсот двадцать дробь одиннадцать тысяч.", p("Набрано: 4 820 / 11 000."))
        assertEquals("набрано сто двадцать дробь триста.", p("Набрано 120/300."))
        assertEquals("набрано сто двадцать дробь триста.", p("Набрано 120 / 300."))
        // слэш вплотную с одной стороны и номер с годом — как было
        assertEquals("ай семь девятьсот двадцать дробь три", p("i7 920/3"))
        assertEquals(false, p("№58 / 2010 г.").contains("дробь"))
        assertEquals(false, p("7,5 / 2,5 = 3.").contains("вторых"))
        assertEquals(false, p("10 / 2 = 5").contains("вторых"))
        // цепочка через слэш с пробелами и буква за знаменателем — не дробь, как было
        assertEquals("цены десять двадцать тридцать рублей.", p("Цены 10 / 20 / 30 рублей."))
        assertEquals(false, p("Дата 12 / 05 / 2020.").contains("дробь"))
        assertEquals(false, p("Подшипник 6204 / 2RS.").contains("вторых"))
        assertEquals(true, p("Тиск 120 / 80").contains("дробь"))
    }
